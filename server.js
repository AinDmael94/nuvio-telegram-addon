app.get('/stream/series/:id.json', (req, res) => {
  const { id } = req.params;
  const parts = id.split(':');

  if (parts.length === 3 && parts[0] === 'running-man') {
    const epNum = parseInt(parts[2], 10);
    const streamUrl = episodeStreams[epNum];

    if (streamUrl) {
      return res.json({
        streams: [
          {
            title: `Running Man - Episod ${epNum}`,
            url: streamUrl
          }
        ]
      });
    }
  }

  res.json({ streams: [] });
});

